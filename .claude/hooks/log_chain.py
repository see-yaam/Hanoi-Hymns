#!/usr/bin/env python
"""
Prompt-chain logger for Claude Code (hackathon requirement).

Registered in .claude/settings.json for two hook events:
  * UserPromptSubmit -> appends the user's prompt to ai-logs/claude-code-log.md
  * Stop             -> reads the session transcript and appends every assistant
                        text block + a short record of each tool call made since
                        the last user prompt.

Design rules:
  * Never break Claude Code: everything is wrapped in try/except, always exit 0.
  * Never leak secrets: secret-looking strings are redacted before writing.
  * Never print to stdout (stdout of UserPromptSubmit is injected into context).
"""
import datetime
import io
import json
import os
import re
import sys
import time

TOOL_INPUT_MAX = 300      # chars of tool input recorded per tool call
LOG_NAME = "claude-code-log.md"
STATE_NAME = ".chain_state.json"

SECRET_PATTERNS = [
    (re.compile(r"github_pat_[A-Za-z0-9_]{20,}"), "github_pat_[REDACTED]"),
    (re.compile(r"gh[pousr]_[A-Za-z0-9]{20,}"), "gh*_[REDACTED]"),
    (re.compile(r"sk-(?:ant-)?[A-Za-z0-9_\-]{16,}"), "sk-[REDACTED]"),
    (re.compile(r"AKIA[0-9A-Z]{16}"), "AKIA[REDACTED]"),
    (re.compile(r"xox[abprs]-[A-Za-z0-9\-]{10,}"), "xox-[REDACTED]"),
    (re.compile(r"(?i)(bearer\s+)[A-Za-z0-9\-\._~\+/]{20,}=*"), r"\1[REDACTED]"),
    (re.compile(r"(?i)\b(password|passwd|pwd|secret|token|api[_-]?key|access[_-]?key)(\s*[=:]\s*)(\"[^\"]*\"|'[^']*'|[^\s,;&]+)"),
     r"\1\2[REDACTED]"),
]


def redact(text):
    if not text:
        return text
    for pattern, repl in SECRET_PATTERNS:
        text = pattern.sub(repl, text)
    return text


def now():
    return datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S (UTC%z)")


def project_dir(payload):
    return (os.environ.get("CLAUDE_PROJECT_DIR")
            or payload.get("cwd")
            or os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def load_state(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {"prompt_count": 0, "logged_uuids": []}


def save_state(path, state):
    try:
        state["logged_uuids"] = state.get("logged_uuids", [])[-500:]
        with open(path, "w", encoding="utf-8") as f:
            json.dump(state, f)
    except Exception:
        pass


def append(log_path, text):
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    new_file = not os.path.exists(log_path)
    with open(log_path, "a", encoding="utf-8", newline="\n") as f:
        if new_file:
            f.write("# Claude Code Prompt Chain Log\n\n"
                    "Auto-generated by `.claude/hooks/log_chain.py` "
                    "(UserPromptSubmit + Stop hooks). Secrets are redacted.\n\n")
        f.write(text)


# ---------------------------------------------------------------- transcript

def read_transcript(path):
    entries = []
    if not path or not os.path.exists(path):
        return entries
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entries.append(json.loads(line))
            except Exception:
                continue
    return entries


def is_real_user_prompt(entry):
    if entry.get("type") != "user" or entry.get("isMeta"):
        return False
    msg = entry.get("message") or {}
    content = msg.get("content")
    if isinstance(content, str):
        return bool(content.strip())
    if isinstance(content, list):
        has_text = any(isinstance(b, dict) and b.get("type") == "text" for b in content)
        has_tool_result = any(isinstance(b, dict) and b.get("type") == "tool_result" for b in content)
        return has_text and not has_tool_result
    return False


def summarize_tool(block):
    name = block.get("name", "tool")
    inp = block.get("input", {})
    try:
        if isinstance(inp, dict):
            # Prefer the most informative field when present
            for key in ("description", "command", "file_path", "pattern", "url", "query", "prompt"):
                if key in inp and isinstance(inp[key], str):
                    s = "%s: %s" % (key, inp[key])
                    break
            else:
                s = json.dumps(inp, ensure_ascii=False)
            if "description" in inp and "command" in inp:
                s = "%s — `%s`" % (inp["description"], inp["command"])
        else:
            s = json.dumps(inp, ensure_ascii=False)
    except Exception:
        s = str(inp)
    s = s.replace("\r", " ").replace("\n", " ⏎ ")
    if len(s) > TOOL_INPUT_MAX:
        s = s[:TOOL_INPUT_MAX] + " …"
    return "- 🔧 **%s** — %s" % (name, s)


def collect_response(entries, already_logged):
    """Return (parts, uuids) for assistant output since the last real user prompt."""
    start = 0
    for i, e in enumerate(entries):
        if is_real_user_prompt(e):
            start = i + 1
    parts, uuids = [], []
    for e in entries[start:]:
        if e.get("type") != "assistant":
            continue
        uid = e.get("uuid")
        if uid and uid in already_logged:
            continue
        msg = e.get("message") or {}
        content = msg.get("content")
        blocks = content if isinstance(content, list) else [{"type": "text", "text": content or ""}]
        for b in blocks:
            if not isinstance(b, dict):
                continue
            if b.get("type") == "text" and (b.get("text") or "").strip():
                parts.append(("text", b["text"].strip()))
            elif b.get("type") == "tool_use":
                parts.append(("tool", summarize_tool(b)))
        if uid:
            uuids.append(uid)
    return parts, uuids


def format_parts(parts):
    out, tools = [], []
    for kind, val in parts:
        if kind == "tool":
            tools.append(val)
        else:
            if tools:
                out.append("<details><summary>Tool calls (%d)</summary>\n\n%s\n\n</details>" % (len(tools), "\n".join(tools)))
                tools = []
            out.append(val)
    if tools:
        out.append("<details><summary>Tool calls (%d)</summary>\n\n%s\n\n</details>" % (len(tools), "\n".join(tools)))
    return "\n\n".join(out)


# ---------------------------------------------------------------- handlers

def handle_prompt(payload, log_path, state):
    prompt = payload.get("prompt", "")
    state["prompt_count"] = int(state.get("prompt_count", 0)) + 1
    n = state["prompt_count"]
    append(log_path, "\n---\n\n## 🧑 Prompt %d — %s\n\n%s\n\n" % (n, now(), redact(prompt).rstrip()))


def handle_stop(payload, log_path, state):
    transcript = payload.get("transcript_path")
    already = set(state.get("logged_uuids", []))
    parts, uuids = [], []
    # The transcript may still be flushing when Stop fires: retry briefly.
    for _ in range(4):
        entries = read_transcript(transcript)
        parts, uuids = collect_response(entries, already)
        if parts:
            break
        time.sleep(0.5)
    if not parts:
        return
    n = max(int(state.get("prompt_count", 0)), 1)
    continued = state.get("last_response_for") == n
    title = "## 🤖 Response %d%s — %s" % (n, " (continued)" if continued else "", now())
    append(log_path, "%s\n\n%s\n\n" % (title, redact(format_parts(parts))))
    state["last_response_for"] = n
    state["logged_uuids"] = list(state.get("logged_uuids", [])) + uuids


def main():
    raw = sys.stdin.buffer.read() if hasattr(sys.stdin, "buffer") else sys.stdin.read()
    if isinstance(raw, bytes):
        raw = raw.decode("utf-8", errors="replace")
    payload = json.loads(raw) if raw.strip() else {}
    event = payload.get("hook_event_name") or (sys.argv[1] if len(sys.argv) > 1 else "")
    base = project_dir(payload)
    log_dir = os.path.join(base, "ai-logs")
    log_path = os.path.join(log_dir, LOG_NAME)
    state_path = os.path.join(log_dir, STATE_NAME)
    state = load_state(state_path)
    ev = event.lower()
    if ev in ("userpromptsubmit", "prompt"):
        handle_prompt(payload, log_path, state)
    elif ev in ("stop", "subagentstop"):
        if ev == "subagentstop":
            return
        handle_stop(payload, log_path, state)
    save_state(state_path, state)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # never break Claude Code
        try:
            err_path = os.path.join(os.environ.get("CLAUDE_PROJECT_DIR", "."), "ai-logs", ".hook_errors.log")
            with io.open(err_path, "a", encoding="utf-8") as f:
                f.write("%s %r\n" % (now(), exc))
        except Exception:
            pass
    sys.exit(0)
